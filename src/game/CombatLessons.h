inline std::string action(int i, const Bindings& b) {
    switch(i) {
        case 0:return b.label(Act::PARRY)+" AS A SHOT REACHES YOU. AIM THE RETURN AT ITS OWNER.";
        case 1:return b.label(Act::INTERACT)+" NEAR A GLOWING ENEMY. THIS TARGET IS ALREADY WOUNDED.";
        case 2:return b.label(Act::GRAPPLE)+" ON THE GUNNER ABOVE. LIGHT ENEMIES COME TO YOU.";
        case 3:return "SELECT 2. LOOK DOWN AND FIRE RMB WITH TWO SHELLS LOADED.";
        case 4:return b.label(Act::GRENADE)+" THEN "+b.label(Act::PARRY)+" WHILE YOUR GRENADE IS WITHIN REACH.";
        case 5:return "CHAIN KILLS, PARRIES AND DIFFERENT WEAPONS TO FILL YOUR STYLE METER. WHEN READY, ATTACK AN ACTIVE TARGET TO UNLEASH OVERDRIVE.";
        case 6:return "REACH THE GOLD PLATFORM. JUMP TWICE, DASH OR GRAPPLE THE OVERHEAD RAIL.";
        case SWORD_COMBO:return "SELECT 5. LAND ALL THREE CUTS: LEFT, RIGHT, THEN OVERHEAD. CLICK AGAIN DURING A CUT TO QUEUE THE NEXT.";
        case SWORD_BLOCK:return "SELECT 5. HOLD RMB BEFORE THE SHOT ARRIVES. KEEP THE ENEMY IN FRONT AND WATCH YOUR GUARD METER.";
        case SWORD_RIPOSTE:return "SELECT 5. TAP RMB AS THE SHOT REACHES YOU, THEN LAND A CUT WITHIN ONE SECOND.";
        case SPLINTER:return b.label(Act::GRENADE)+" THROWS A SPLINTER. SHOOT THE CYAN SHARD IN MID-AIR TO REDIRECT YOUR ROUND INTO THE TARGET.";
        case SPLINTER_CHAIN:return "THROW TWO SPLINTERS WITH "+b.label(Act::GRENADE)+". SHOOT ONE WHILE BOTH ARE IN THE AIR TO CHAIN THE ROUND.";
        case RECALL:return b.label(Act::RECALL)+" LEAVES YOUR STATUE. MOVE AT LEAST 3 METRES, THEN PRESS "+b.label(Act::RECALL)+" AGAIN WITHIN 8 SECONDS TO RETURN.";
        case SLIDE_KICK:return "RUN TOWARD THE TARGET, THEN HOLD "+b.label(Act::SLIDE)+" TO SLIDE INTO ITS LEGS.";
        case SLAM:return "STEP OFF THE CYAN LEDGE TOWARD THE TARGET. HOLD "+b.label(Act::SLIDE)+" IN THE AIR TO SLAM DOWN NEAR IT.";
        case PRECISION:return "SELECT 3 OR 4, HOLD RMB TO AIM, THEN LAND A HEADSHOT ON THE STILL TARGET.";
        case ALT_FIRE:return "SELECT 1 AND PRESS RMB TO FAN THE CYLINDER. SELECT 2 FOR A DOUBLE-BARREL SHOT.";
        case HEAVY_GRAPPLE:return "AIM AT THE BRUTE AND PRESS "+b.label(Act::GRAPPLE)+". HEAVY TARGETS PULL YOU TO THEM; "+b.label(Act::JUMP)+" RELEASES.";
        case SHIELD_COUNTER:return "GET ABOVE OR BESIDE THE SHIELD. LAND A SHOT IN THE HEAD OR EXPOSED BODY.";
        default:return "TRY ALL GUNS, MODS AND THE SWORD. "+b.label(Act::GRENADE)+" SPLINTER / "+b.label(Act::RECALL)+" RECALL. [ / ] SELECT A TARGET. BACKSPACE REPEATS.";
    }
}
